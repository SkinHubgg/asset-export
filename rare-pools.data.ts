/**
 * The ★ RARE-SPECIAL POOLS — which knives and gloves a case can drop, and the second of the two
 * things `skins.json` needs that the game files do not contain.
 *
 * WHY THIS EXISTS
 * ---------------
 * A case's ordinary contents are in `items_game`: `revolving_loot_lists` maps the case's series
 * number to a `client_loot_lists` name, and that list (recursively, through its `_rare` / `_mythical`
 * / `_legendary` / `_ancient` sub-lists) names every `[paintkit]weapon` inside. The ★ tier is
 * different. Valve REFERENCES the rare pool by name and never ships its contents: `set_glove_3_unusual`,
 * `community_case_6_unusual`, `unusual_revolving_list` and 17 others are dangling references, 182
 * dangling loot-list names in all. Measured: deriving crates from `items_game` alone leaves 556 knife
 * rows and 94 glove rows with an EMPTY crate list.
 *
 * `ByMykel/CSGO-API` has exactly the same problem and solves it exactly this way — `utils/rareSpecial.js`
 * is a 36 KB hand-maintained map. So this is not a shortcut around a derivation we failed to find; it
 * is the only way anyone does it.
 *
 * WHAT IS AND IS NOT DATA HERE
 * ----------------------------
 * Only the POOL CONTENTS are checked in. Which crates draw from which pool stays derived — 359 crate
 * items reach a pool through their loot list's dangling sub-reference or their item set's
 * `unusuals.unique`, both read live out of `items_game`. So a new case that reuses an existing pool
 * needs no edit here; only a new pool does.
 *
 * SEEDED AND VERIFIED
 * -------------------
 * Extracted from the `ByMykel/CSGO-API` `skins.json` of 2026-08-07 — the last copy fetched before the
 * exporter stopped downloading it — by inverting each ★ row's own crate list. Feeding these 20 pools
 * back through the live crate->pool map reproduces the crate list of all 670 ★ rows — 650 painted plus the 20
 * vanilla knives — with ZERO differences. `gamedata.test.ts` re-runs that check, with a negative control.
 *
 * `[vanilla]weapon_bayonet` and its 27 siblings are real entries here even though `items_game` has no
 * such loot key: an UNPAINTED knife drops from the same cases as its finishes, and nothing in the
 * game files says so.
 *
 * A pool that loses an entry silently drops a case from a knife's "found in" list, so
 * `buildSkins` reports any pool name it can no longer find rather than emitting an empty list.
 */

